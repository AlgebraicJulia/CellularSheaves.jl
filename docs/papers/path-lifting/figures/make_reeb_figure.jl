# Generates figures/reeb_cells.tex: the cells of a small grid map coloured by a band
# of agent j's cost-to-go d_j, split into its connected components (Reeb arcs).
# Plain Julia, no packages. Run: julia figures/make_reeb_figure.jl (from the paper directory).

const NX, NY = 17, 9
const WALL_ROW = 4
const GAP = (1, NX)                # the wall runs along row WALL_ROW except at both ends
const GOAL = (9, 1)                 # agent j's goal, below the middle of the wall
const BAND = (14, 16)               # the band band of d_j that is drawn

free(x, y) = 1 <= x <= NX && 1 <= y <= NY && !(y == WALL_ROW && x ∉ GAP)

function distances()
    d = fill(typemax(Int), NX, NY)
    d[GOAL...] = 0
    queue = [GOAL]
    while !isempty(queue)
        (x, y) = popfirst!(queue)
        for (dx, dy) in ((1, 0), (-1, 0), (0, 1), (0, -1))
            u, v = x + dx, y + dy
            if free(u, v) && d[u, v] == typemax(Int)
                d[u, v] = d[x, y] + 1
                push!(queue, (u, v))
            end
        end
    end
    return d
end

# Connected components of the band (4-neighbour adjacency among band cells).
function components(inband)
    label = zeros(Int, NX, NY)
    n = 0
    for x in 1:NX, y in 1:NY
        (inband[x, y] && label[x, y] == 0) || continue
        n += 1
        stack = [(x, y)]
        label[x, y] = n
        while !isempty(stack)
            (a, b) = pop!(stack)
            for (dx, dy) in ((1, 0), (-1, 0), (0, 1), (0, -1))
                u, v = a + dx, b + dy
                if 1 <= u <= NX && 1 <= v <= NY && inband[u, v] && label[u, v] == 0
                    label[u, v] = n
                    push!(stack, (u, v))
                end
            end
        end
    end
    return label, n
end

d = distances()
inband = [free(x, y) && BAND[1] <= d[x, y] <= BAND[2] for x in 1:NX, y in 1:NY]
label, ncomp = components(inband)
@assert ncomp == 2 "choose a band with exactly two components (got $ncomp)"

open(joinpath(@__DIR__, "reeb_cells.tex"), "w") do io
    println(io, "% Generated by figures/make_reeb_figure.jl; do not edit by hand.")
    println(io, "% Grid $(NX)×$(NY), wall on row $WALL_ROW except columns $GAP, goal $GOAL, band d_j ∈ $BAND.")
    for x in 1:NX, y in 1:NY
        free(x, y) || continue
        style = inband[x, y] ? (label[x, y] == 1 ? "arcA" : "arcB") : "cellfree"
        println(io, "\\path[$style] ($(x - 1),$(y - 1)) rectangle ++(1,1);")
    end
    for x in 1:NX
        free(x, WALL_ROW) || println(io, "\\path[wall] ($(x - 1),$(WALL_ROW - 1)) rectangle ++(1,1);")
    end
    println(io, "\\node[goal] at ($(GOAL[1] - 0.5),$(GOAL[2] - 0.5)) {};")
end
println("band d_j ∈ $BAND has $ncomp components; sizes ", [count(==(c), label) for c in 1:ncomp])
